-- Approved business fields for the customer single source of truth.
-- Mapping, recognition, and Smart Sheet write-back are configured separately.
ALTER TABLE customers
  ADD COLUMN customer_name VARCHAR(100) DEFAULT NULL COMMENT '客户姓名' AFTER nickname,
  ADD COLUMN advertising_type VARCHAR(100) DEFAULT NULL COMMENT '广告类型' AFTER platform_lead_at,
  ADD COLUMN global_advertisement_id VARCHAR(100) DEFAULT NULL COMMENT '全域广告ID' AFTER advertising_type,
  ADD COLUMN standard_advertisement_id VARCHAR(100) DEFAULT NULL COMMENT '标准广告ID' AFTER global_advertisement_id,
  ADD COLUMN content_id VARCHAR(100) DEFAULT NULL COMMENT '内容ID' AFTER standard_advertisement_id,
  ADD COLUMN video_id VARCHAR(100) DEFAULT NULL COMMENT '视频ID' AFTER content_id,
  ADD COLUMN order_number VARCHAR(100) DEFAULT NULL COMMENT '订单号' AFTER video_id,
  ADD COLUMN conversion_trace VARCHAR(500) DEFAULT NULL COMMENT '转化追溯' AFTER order_number,
  ADD COLUMN previous_assigned_keeper VARCHAR(100) DEFAULT NULL COMMENT '上次分配人' AFTER assigned_at,
  ADD COLUMN previous_platform_lead_at DATETIME DEFAULT NULL COMMENT '上次留资时间' AFTER previous_assigned_keeper,
  ADD COLUMN assignment_month VARCHAR(20) DEFAULT NULL COMMENT '分配月份' AFTER previous_platform_lead_at,
  ADD COLUMN experience_card_type VARCHAR(50) DEFAULT NULL COMMENT '体验卡类型' AFTER purchased_project,
  ADD COLUMN pending_order_status VARCHAR(100) DEFAULT NULL COMMENT '挂单情况' AFTER experience_card_type,
  ADD COLUMN purchase_date DATE DEFAULT NULL COMMENT '购卡时间' AFTER pending_order_status,
  ADD COLUMN customer_level VARCHAR(20) DEFAULT NULL COMMENT '客户等级' AFTER purchase_date,
  ADD COLUMN arrival_handover_record TEXT DEFAULT NULL COMMENT '到店衔接记录' AFTER arrival_source_row_id,
  ADD COLUMN arrival_project_type VARCHAR(100) DEFAULT NULL COMMENT '项目类型' AFTER arrival_handover_record,
  ADD COLUMN arrival_experience_project VARCHAR(500) DEFAULT NULL COMMENT '到店体验项目' AFTER arrival_project_type,
  ADD COLUMN historical_experience_count VARCHAR(100) DEFAULT NULL COMMENT '历史体验次数' AFTER arrival_experience_project,
  ADD COLUMN customer_report TEXT DEFAULT NULL COMMENT '客户报告' AFTER historical_experience_count,
  ADD COLUMN reception_teacher VARCHAR(100) DEFAULT NULL COMMENT '接待老师' AFTER customer_report,
  ADD COLUMN reception_consultant VARCHAR(100) DEFAULT NULL COMMENT '接待顾问' AFTER reception_teacher,
  ADD COLUMN voucher_redeemed VARCHAR(20) DEFAULT NULL COMMENT '是否核券' AFTER reception_consultant,
  ADD COLUMN transaction_amount DECIMAL(12,2) DEFAULT NULL COMMENT '成交金额' AFTER voucher_redeemed,
  ADD COLUMN transaction_at DATETIME DEFAULT NULL COMMENT '成交时间' AFTER transaction_amount,
  ADD COLUMN transaction_primary_reason VARCHAR(500) DEFAULT NULL COMMENT '成交主因' AFTER transaction_at;
